def compact(text):
 return re.sub(r'\s+','',html.unescape(re.sub('<[^>]+>',' ',text)))

def classify_chapter(q):
 # Headline excludes choices and data tables, avoiding distractor-based labels.
 head=q['html'].split('<table')[0].split('<div class="table-scroll">')[0]
 # Keep the complete question stem (including requested calculation), not options.
 stem=compact(head).split('?')[0]
 rules=FINANCIAL if q['subject']=='재무회계' else TAX
 for cid,pattern in rules:
  if re.search(pattern,stem):return cid,'rule'
 for cid,pattern in rules:
  if re.search(pattern,compact(q['raw'])):return cid,'review'
 return ('F0-0' if q['subject']=='재무회계' else 'T0-0'),'review'

def apply(questions,root):
 overrides_path=root/'content/chapter-overrides.json'
 overrides=json.loads(overrides_path.read_text()) if overrides_path.exists() else {}
 lookup={c['id']:c for c in CHAPTERS}
 for q in questions:
  cid,status=classify_chapter(q)
  if q['id'] in overrides:cid,status=overrides[q['id']],'reviewed'
  assert cid in lookup or cid in ('F0-0','T0-0'),(q['id'],cid)
  if cid in lookup:assert lookup[cid]['subject']==q['subject'],q['id']
  q.update(chapterId=cid,classificationStatus=status)
  if cid in lookup:
   c=lookup[cid];q.update(partName=c['partName'],chapterName=c['chapterName'])
  else:q.update(partName='분류 확인 필요',chapterName='분류 확인 필요')
 (root/'dist/curriculum.json').write_text(json.dumps(CHAPTERS,ensure_ascii=False,indent=2))
